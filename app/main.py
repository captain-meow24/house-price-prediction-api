(PROJECT / "app" / "main.py").write_text(textwrap.dedent('''
    import os
    import joblib
    import pandas as pd
    from fastapi import FastAPI, HTTPException
    from pydantic import BaseModel, Field
    from typing import Any

    MODEL_PATH = os.getenv("MODEL_PATH", "model.joblib")

    app = FastAPI(
        title="House Price Prediction API",
        description="Predict house sale prices using a model trained on Kaggle's House Prices dataset.",
        version="1.0.0"
    )

    class PredictionRequest(BaseModel):
        features: dict[str, Any] = Field(
            ...,
            description="House features such as OverallQual, GrLivArea, GarageCars and YearBuilt."
        )

    def load_artifact():
        if not os.path.exists(MODEL_PATH):
            raise FileNotFoundError(
                f"Model file not found at {MODEL_PATH}. Train the model first."
            )
        return joblib.load(MODEL_PATH)

    @app.get("/")
    def home():
        return {
            "message": "House Price Prediction API is running",
            "docs": "/docs",
            "prediction_endpoint": "POST /predict"
        }

    @app.get("/health")
    def health():
        return {"status": "healthy"}

    @app.post("/predict")
    def predict(request: PredictionRequest):
        try:
            artifact = load_artifact()
            feature_names = artifact["feature_names"]

            unknown = set(request.features) - set(feature_names)
            if unknown:
                raise HTTPException(
                    status_code=422,
                    detail=f"Unknown feature names: {sorted(unknown)}"
                )

            # Fill omitted fields with missing values. The trained pipeline
            # handles missing numeric and categorical values using imputers.
            row = {name: None for name in feature_names}
            row.update(request.features)
            input_df = pd.DataFrame([row], columns=feature_names)

            prediction = artifact["model"].predict(input_df)[0]

            return {
                "predicted_sale_price": round(float(prediction), 2),
                "currency": "USD"
            }

        except HTTPException:
            raise
        except FileNotFoundError as exc:
            raise HTTPException(status_code=503, detail=str(exc))
        except Exception as exc:
            raise HTTPException(status_code=500, detail=str(exc))
''').lstrip())

